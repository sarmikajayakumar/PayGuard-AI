import { ScreenshotAnalysisResult } from '@/types';

/**
 * Parses OCR extracted text from a payment screenshot and checks for critical anomalies
 */
export function analyzeExtractedReceiptText(extractedText: string): ScreenshotAnalysisResult {
  const text = extractedText.trim();
  const anomalyWarnings: string[] = [];
  const verificationGuidance: string[] = [];

  // 1. Payment Status Detection
  let paymentStatus: ScreenshotAnalysisResult['paymentStatus'] = 'UNKNOWN';
  if (/(?:paid\s+successfully|payment\s+successful|successful|success|completed|transfer\s+successful|பரிவர்த்தனை\s+வெற்றி)/i.test(text)) {
    paymentStatus = 'SUCCESS';
  } else if (/(?:processing|pending|in\s*progress|payment\s*initiated)/i.test(text)) {
    paymentStatus = 'PROCESSING';
  } else if (/(?:failed|declined|cancelled|unsuccessful|rejected)/i.test(text)) {
    paymentStatus = 'FAILED';
  }

  // 2. Amount Extraction (₹, INR, Rs., or plain digits with currency context)
  let amount: string | null = null;
  const amountMatch = text.match(/(?:₹|inr|rs\.?)\s*([\d,]+(?:\.\d{2})?)/i) ||
                      text.match(/amount[:\s]*(?:₹|inr|rs\.?)?\s*([\d,]+(?:\.\d{2})?)/i) ||
                      text.match(/\b([\d,]{2,}\.\d{2})\b/);
  if (amountMatch) {
    amount = `₹${amountMatch[1].replace(/,/g, '')}`;
  }

  // 3. Indian UPI 12-digit UTR / Reference ID Extraction
  let utr: string | null = null;
  // Authentic Indian UPI transactions feature a 12-digit numerical UTR
  const utrMatch = text.match(/(?:utr|ref(?:\s*no|\s*id)?|upi\s*ref(?:erence)?(?:\s*no)?|txn(?:\s*id)?|transaction\s*id)[\s:.-]*([0-9]{12})\b/i) ||
                   text.match(/\b([0-9]{12})\b/);
  if (utrMatch) {
    utr = utrMatch[1];
  }

  // 4. Date & Time Extraction
  let date: string | null = null;
  const dateMatch = text.match(/\b(\d{1,2}[\s/-](?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec|[0-9]{1,2})[\s/-]\d{2,4}(?:[,\s]+\d{1,2}:\d{2}(?::\d{2})?\s*(?:am|pm)?)?)\b/i) ||
                    text.match(/\b(\d{1,2}:\d{2}\s*(?:am|pm)?,\s*\d{1,2}\s+[a-z]{3}\s+\d{4})\b/i);
  if (dateMatch) {
    date = dateMatch[1];
  }

  // 5. Recipient / Sender UPI ID (VPA)
  let recipient: string | null = null;
  let sender: string | null = null;
  const vpaMatches = text.match(/[a-zA-Z0-9._-]+@[a-zA-Z]{3,}/g);
  if (vpaMatches && vpaMatches.length > 0) {
    recipient = vpaMatches[0];
    if (vpaMatches.length > 1) {
      sender = vpaMatches[1];
    }
  }

  // ANOMALY DETECTION FOR FAKE PAYMENT SPOOFS:
  // Many Indian fraudsters use fake APK apps (such as "Paytm Spoon", "Spoof Paytm", "GPay Fake")
  // to fool shopkeepers into believing they sent money.
  let riskScore = 20; // Default baseline caution: visual proof is never authoritative

  // Check for presence of UTR
  if (!utr) {
    anomalyWarnings.push('Missing 12-digit UPI UTR number: Authentic Indian UPI transaction receipts always generate a 12-digit numerical reference number (UTR).');
    riskScore += 35;
  } else if (utr === '123456789012' || utr === '000000000000' || /^(\d)\1{11}$/.test(utr)) {
    anomalyWarnings.push(`Repeated / Mock UTR Pattern detected ("${utr}"): This matches dummy reference numbers generated by fake payment mock apps.`);
    riskScore += 45;
  }

  // Check for spoof generator watermark or debug words
  if (/(?:spoof|fake|prank|mock|generator|screenshot\s*editor|clone|sample)/i.test(text)) {
    anomalyWarnings.push('Malicious keyword detected in receipt: Contains terms associated with counterfeit screenshot apps.');
    riskScore += 50;
  }

  // Check for absent recipient or sender bank details
  if (!recipient && !sender && !/(?:bank|a\/c|account)/i.test(text)) {
    anomalyWarnings.push('Vague banking footprint: Receipt lacks clear sender/recipient bank account or UPI ID references.');
    riskScore += 15;
  }

  // If status is not even Success
  if (paymentStatus === 'PROCESSING') {
    anomalyWarnings.push('Transaction status is PENDING / PROCESSING: Money has NOT yet been credited to the destination account.');
    riskScore += 25;
  } else if (paymentStatus === 'FAILED') {
    anomalyWarnings.push('Transaction status is FAILED: The payment did not execute.');
    riskScore += 60;
  }

  riskScore = Math.min(100, Math.max(15, riskScore));

  const riskLevel = riskScore >= 60 ? 'high' : riskScore >= 30 ? 'suspicious' : 'low';

  verificationGuidance.push('DO NOT rely on the customer/buyer showing their phone screen.');
  verificationGuidance.push('Check your own official bank SMS notification or your UPI merchant soundbox.');
  verificationGuidance.push('Open your own Google Pay / PhonePe / Paytm / BHIM app and refresh the transaction history.');
  verificationGuidance.push('Verify that the 12-digit UTR on your bank passbook matches before releasing goods or services.');

  return {
    id: `ocr-${Date.now()}`,
    timestamp: new Date().toISOString(),
    extractedText: text || 'No readable text identified.',
    paymentStatus,
    amount,
    utr,
    date,
    recipient,
    sender,
    riskScore,
    riskLevel,
    anomalyWarnings,
    verificationGuidance,
    disclaimer: 'CRITICAL CYBERSECURITY NOTICE: A screenshot alone can NEVER prove that money has reached your bank account. Digital images are easily fabricated with spoof APK apps or edited in seconds. Always verify credited funds directly in your own official bank or UPI app.',
  };
}
